            assert.is_true(sent("n"))
            room(THREE)
            helper.fireTimers(1000)
            clearSent()
            room(THREE)
            assert.is_true(sent("confer kill champion"))
        end)

        it("leaves alone what was lying there before the trip", function()
            startLoop(NONE)
            group("Ready", 100, "n,s")
            helper.simulateLine("There is a coil of rope lying on the floor.")
