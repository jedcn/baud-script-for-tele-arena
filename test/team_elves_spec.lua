                for _, call in ipairs(helper.sendCalls) do
                    if call == "confer report-xp" then asked = asked + 1 end
                end
                assert.are.equal(1, asked)
            end)

            it("a follower answers with a fresh reading", function()
                taPackage.followTarget = "pelayo"
