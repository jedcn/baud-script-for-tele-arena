        -- Everyone Ready at once, with no time gone by since the room printed.
        local function readyNow(exits)
            helper.simulateLine("Your group currently consists of:")
            helper.simulateLine("  Pelayo                         (L) [HE:100% ST:Ready]")
            helper.simulateLine("Exits: " .. exits .. ".")
        end

        local TRIP = "In your haste, you trip and fall!"

        local function walkedIntoOne()
            startLoop(NONE)
            group("Ready", 100, "n,s")
            room(NONE)
            clearSent()
        end

        it("waits navigate-to's pace after walking into a room", function()
            walkedIntoOne()
            readyNow("n,s")
            assert.is_false(sent("n"))
            readyNow("n,s")
            helper.fireTimers(taPackage.navStepDelayMs)
            assert.is_true(sent("n"))
        end)

        it("does not wait when the pace has already gone by", function()
            walkedIntoOne()
            helper.advanceMs(taPackage.navStepDelayMs)
            readyNow("n,s")
            assert.is_true(sent("n"))
        end)

        it("calls off a waiting move when it casts a heal", function()
            walkedIntoOne()
            readyNow("n,s")
            group("Resting", 80, "n,s")
            assert.is_true(sent("cast kusamotumaru"))
            helper.fireTimers(taPackage.navStepDelayMs)
            assert.is_false(sent("n"))
        end)

        it("calls off a waiting move when a champion catches it", function()
            walkedIntoOne()
            readyNow("n,s")
            helper.simulateLine("An elven champion has just arrived from the south.")
            helper.fireTimers(taPackage.navStepDelayMs)
            assert.is_false(sent("n"))
        end)

        it("after a trip, looks at the floor, picks up what fell, and goes again", function()
            walkedIntoOne()
            helper.advanceMs(taPackage.navStepDelayMs)
            readyNow("n,s")
            helper.simulateLine(TRIP)
            clearSent()
