            helper.simulateLine("There is a coil of rope lying on the floor.")
            assert.is_false(sent("get coil"))
            assert.is_false(sent("get rope"))
            helper.fireTimers(taPackage.navStepDelayMs)
            assert.is_true(sent("n"))
        end)

