-- team_elves_spec.lua
-- team-fight-elves: the wording here is taken from logs of the group doing
-- this by hand (logs/session-pelayo-2026-11-01T21-53-00.log).

local helper = require("test.test_helper")

local THREE = "There are three elven champions here."
local TWO = "There are two elven champions here."
local ONE = "There is an elven champion here."
local NONE = nil
local WARRIORS = "There are two elven warriors here."
local MIXED = "There are two elven champions, and an elven warrior here."
local WARRIOR = "There is an elven warrior here."

describe("team-fight-elves", function()

    before_each(function()
        helper.resetAll()
        dofile("main.lua")
        taPackage.character.setClass("High Priest")
    end)

    local function room(occupants)
        if occupants then helper.simulateLine(occupants) end
        helper.simulateLine("Kerhak, Castor, Pollux, and Teekywiki are here.")
        helper.simulateLine("There is nothing on the floor.")
    end

    -- A poll that finds everyone Ready comes a poll after the last one, so it is
    -- past the walking pace too.
    local function group(state, health, exits)
        if state == "Ready" then helper.advanceMs(3000) end
        helper.simulateLine("Your group currently consists of:")
        helper.simulateLine("  Pelayo                         (L) [HE:100% ST:" .. state .. "]")
        helper.simulateLine("  Pollux                             [HE:" .. (health or 100) .. "% ST:" .. state .. "]")
        helper.simulateLine("Exits: " .. (exits or "e,w") .. ".")
    end

    local function sent(text)
        for _, call in ipairs(helper.sendCalls) do
            if call == text then return true end
        end
        return false
    end

    local function clearSent()
        for k in pairs(helper.sendCalls) do helper.sendCalls[k] = nil end
    end

    local function lastEcho()
        return helper.echoCalls[#helper.echoCalls]
    end

    local function start(occupants)
        helper.simulateAlias("team-fight-elves")
        room(occupants or THREE)
    end

    local function kill()
        helper.simulateLine("The elven champion falls to the ground lifeless!")
    end

    -- A champion leaves, the rest die, and the group musters for the chase.
    local function fleeWestThenClear()
        start()
        helper.simulateLine("The elven champion has just gone to the west.")
        kill()
        room(TWO)
        kill()
        room(ONE)
        kill()
        room(NONE)
    end

    -- The room prints on arrival, then again for the scan once followers land.
    local function arrive(occupants)
        room(occupants)
        helper.fireTimers(1000)
        room(occupants)
    end

    describe("countElves", function()
        local count = function(s) return taPackage.teamElves.countElves(s) end

        it("reads the occupant line", function()
            assert.are.equal(1, count("an elven champion").champion)
            assert.are.equal(3, count("three elven champions").champion)
            assert.are.equal(5, count("five elven champions").total)
            assert.are.equal(1, count("an elven warrior").warrior)
            assert.are.equal(2, count("two elven warriors").warrior)
        end)

        it("counts each kind in a mixed room", function()
            local c = count("three elven champions, and four elven warriors")
            assert.are.equal(3, c.champion)
            assert.are.equal(4, c.warrior)
            assert.are.equal(7, c.total)
        end)

        it("ignores anything that isn't a champion or a warrior", function()
            assert.are.equal(0, count("a female barbarian").total)
            assert.are.equal(1, count("a female barbarian, and an elven warrior").total)
        end)

        it("treats an unknown count word as more than one", function()
            assert.are.equal(2, count("several elven champions").champion)
        end)
    end)

    describe("warriors", function()
        it("fights a room of warriors", function()
            start(WARRIORS)
            assert.is_true(sent("confer kill warrior"))
            assert.is_true(sent("a warrior"))
        end)

        it("goes for the champions first in a mixed room, then the warriors", function()
            start(MIXED)
            assert.is_true(sent("confer kill champion"))
            assert.is_false(sent("confer kill warrior"))
            kill()
            room("There is an elven champion, and an elven warrior here.")
            kill()
            clearSent()
            room(WARRIOR)
            assert.is_true(sent("confer kill warrior"))
        end)

        it("counts a dead warrior as a kill", function()
            start(WARRIOR)
            helper.simulateLine("The elven warrior falls to the ground lifeless!")
            room(NONE)
            assert.is_false(taPackage.teamElves.running())
            assert.is_truthy(lastEcho():find("1 killed", 1, true))
        end)

        it("doesn't count anything else that dies", function()
            start(WARRIOR)
            helper.simulateLine("The female barbarian falls to the ground lifeless!")
            helper.simulateLine("The elven warrior falls to the ground lifeless!")
            room(NONE)
            assert.is_truthy(lastEcho():find("1 killed", 1, true))
        end)

        it("chases a warrior that flees", function()
            start(WARRIORS)
            helper.simulateLine("The elven warrior has just gone to the west.")
            helper.simulateLine("The elven warrior falls to the ground lifeless!")
            room(NONE)
            group("Ready")
            assert.is_true(sent("w"))
        end)

        it("restarts the kill loop when its warrior walks out", function()
            start(WARRIORS)
            helper.simulateLine('Sorry, you don\'t see "warrior" nearby.')
            assert.is_falsy(taPackage.killActive)
        end)

        it("turns and fights a warrior that catches it between rooms", function()
            fleeWestThenClear()
            helper.simulateLine("An elven warrior has just arrived from the west.")
            clearSent()
            room(WARRIOR)
            assert.is_true(sent("confer kill warrior"))
        end)
    end)

    describe("ringNext", function()
        local nextExit = function(...) return taPackage.teamElves.ringNext(...) end

        it("goes straight on, including through the junction", function()
            assert.are.equal("w", nextExit({ "e", "w" }, "w"))
            assert.are.equal("w", nextExit({ "e", "s", "w" }, "w"))
        end)

        it("turns a corner by the exit we did not come in by", function()
            assert.are.equal("n", nextExit({ "e", "n" }, "w"))
        end)

        it("gives up where the way on is not one exit", function()
            assert.is_nil(nextExit({ "n", "s", "e" }, "w"))
            assert.is_nil(nextExit({ "e" }, "w"))
        end)
    end)

    describe("XP readings at each end of a run", function()
        it("takes one for everyone as a run starts", function()
            helper.simulateAlias("team-fight-elves")
            assert.is_true(sent("status"))
            assert.is_true(sent("confer status"))
        end)

        it("takes one as a run succeeds", function()
            start(ONE)
            kill()
            clearSent()
            room(NONE)
            assert.is_true(sent("status"))
            assert.is_true(sent("confer status"))
        end)

        it("takes one when a run is stopped by hand", function()
            start()
            clearSent()
            helper.simulateAlias("stop-team-fight-elves")
            assert.is_true(sent("confer status"))
        end)

        it("a follower answers the leader's confer", function()
            taPackage.followTarget = "pelayo"
            helper.simulateLine("From Pelayo (to group): status")
            assert.is_true(sent("status"))
        end)

        it("a follower ignores anyone but the leader", function()
            taPackage.followTarget = "pelayo"
            helper.simulateLine("From Kerhak (to group): status")
            assert.is_false(sent("status"))
        end)
    end)

    it("refuses to run without a High Priest", function()
        taPackage.character.setClass("Warrior")
        helper.simulateAlias("team-fight-elves")
        assert.is_false(taPackage.teamElves.running())
    end)

    it("sends the group and the leader at the champions", function()
        start()
        assert.is_true(sent("confer kill champion"))
        assert.is_true(sent("a champion"))
    end)

    it("does not re-engage while the kill loop is running", function()
        start()
        clearSent()
        room(THREE)
        assert.is_false(sent("confer kill champion"))
    end)

    it("re-engages after a death, which ends every kill loop", function()
        start()
        kill()
        clearSent()
        room(TWO)
        assert.is_true(sent("confer kill champion"))
    end)

    it("succeeds once the starting room is empty", function()
        start(ONE)
        kill()
        room(NONE)
        assert.is_false(taPackage.teamElves.running())
        assert.is_truthy(lastEcho():find("1 killed", 1, true))
    end)

    describe("healing", function()
        it("casts group heal when someone is below 85%", function()
            start()
            group("Resting", 84)
            assert.is_true(sent("cast kusamotumaru"))
        end)

        it("leaves a scratch alone", function()
            start()
            group("Resting", 85)
            assert.is_false(sent("cast kusamotumaru"))
        end)

        local HEALED = "You discharged the spell at friendly people in the area, healing 290 damage!"

        it("waits out the spell's recovery after a heal lands", function()
            start()
            group("Resting", 80)
            helper.simulateLine(HEALED)
            clearSent()
            helper.advanceMs(23999)
            group("Resting", 80)
            assert.is_false(sent("cast kusamotumaru"))
            helper.advanceMs(1)
            group("Resting", 80)
            assert.is_true(sent("cast kusamotumaru"))
        end)

        it("counts a heal cast by hand before the run started", function()
            helper.simulateLine(HEALED)
            start()
            group("Resting", 80)
            assert.is_false(sent("cast kusamotumaru"))
        end)

        it("tries again on the next poll if the cast was refused", function()
            start()
            group("Resting", 80)
            helper.simulateLine("You are still too mentally exhausted from your last incantation!")
            clearSent()
            group("Resting", 80)
            assert.is_true(sent("cast kusamotumaru"))
        end)

        it("polls the group during the fight", function()
            start()
            clearSent()
            helper.fireTimers(3000)
            assert.is_true(sent("group"))
        end)
    end)

    describe("chasing", function()
        it("finishes the room before chasing", function()
            start()
            helper.simulateLine("The elven champion has just gone to the west.")
            room(TWO)
            group("Ready")
            assert.is_false(sent("w"))
        end)

        it("stands the group down and waits for everyone to be Ready", function()
            fleeWestThenClear()
            assert.is_true(sent("confer kill-stop"))
            group("Resting")
            assert.is_false(sent("w"))
            group("Ready")
            assert.is_true(sent("w"))
        end)

        it("kills the one it finds next door, then walks back and finishes", function()
            fleeWestThenClear()
            group("Ready")
            clearSent()
            arrive(ONE)
            assert.is_true(sent("confer kill champion"))
            kill()
            room(NONE)
            group("Ready")
            assert.is_true(sent("e"))
            room(NONE)
            assert.is_false(taPackage.teamElves.running())
        end)

        it("follows the ring round a corner when he isn't one room away", function()
            fleeWestThenClear()
            group("Ready")
            room(NONE)
            clearSent()
            group("Ready", 100, "e,n")
            assert.is_true(sent("n"))
        end)

        it("heads home from three or more, and says the chase was given up", function()
            fleeWestThenClear()
            group("Ready")
            clearSent()
            room(THREE)
            assert.is_false(sent("confer kill champion"))
            group("Ready")
            assert.is_true(sent("e"))
            room(NONE)
            assert.is_false(taPackage.teamElves.running())
            assert.is_truthy(lastEcho():find("1 chase(s) given up", 1, true))
        end)

        it("fights two it finds on a chase", function()
            fleeWestThenClear()
            group("Ready")
            clearSent()
            arrive(TWO)
            assert.is_true(sent("confer kill champion"))
            assert.is_false(lastEcho():find("too many", 1, true) ~= nil)
        end)

        it("fights a lone champion on the way home", function()
            fleeWestThenClear()
            group("Ready")
            room(NONE)
            group("Ready")
            room(THREE)
            group("Ready")
            clearSent()
            arrive(ONE)
            assert.is_true(sent("confer kill champion"))
        end)

        it("fights whatever is at home when it gets back", function()
            fleeWestThenClear()
            group("Ready")
            room(THREE)
            group("Ready")
            clearSent()
            arrive(THREE)
            assert.is_true(sent("confer kill champion"))
        end)

        it("gives up after ten rooms and walks all of them back", function()
            fleeWestThenClear()
            for _ = 1, 10 do
                group("Ready")
                room(NONE)
            end
            clearSent()
            group("Ready")
            assert.is_true(sent("e"))
            for _ = 1, 9 do
                room(NONE)
                group("Ready")
            end
            room(NONE)
            assert.is_false(taPackage.teamElves.running())
        end)

        it("turns to follow one that flees from a chase fight", function()
            fleeWestThenClear()
            group("Ready")
            arrive(ONE)
            helper.simulateLine("The elven champion has just gone to the south.")
            kill()
            room(NONE)
            clearSent()
            group("Ready", 100, "e,s,w")
            assert.is_true(sent("s"))
        end)

        it("skips the chase if the champion came back by itself", function()
            start()
            helper.simulateLine("The elven champion has just gone to the west.")
            helper.simulateLine("An elven champion has just arrived from the west.")
            kill()
            room(NONE)
            assert.is_false(taPackage.teamElves.running())
        end)

        it("does not count a move the game refused", function()
            fleeWestThenClear()
            group("Ready")
            helper.simulateLine("You cannot leave in the heat of battle!")
            room(NONE)
            clearSent()
            group("Ready")
            assert.is_true(sent("w"))
            arrive(ONE)
            kill()
            room(NONE)
            group("Ready")
            room(NONE)
            -- One step out, so one step back: the refused move left no trace.
            assert.is_false(taPackage.teamElves.running())
        end)

        it("checks the room when a move goes nowhere, and fights what is there", function()
            fleeWestThenClear()
            group("Ready")
            clearSent()
            helper.fireTimers(3000)
            helper.fireTimers(3000)
            helper.fireTimers(3000)
            assert.is_true(taPackage.teamElves.running())
            room(THREE)
            assert.is_true(sent("confer kill champion"))
        end)
    end)

    -- logs/session-pelayo-2026-11-07T14-58-23.log, 15:01:56: a chase found three,
    -- turned back, and they followed. The heal and the move went out together,
    -- the move was refused, and the run gave up with all three in the room.
    describe("caught on the way back", function()
        local REST = "Sorry, you'll have to rest a while before you can move."
        local ARRIVED = "An elven champion has just arrived from the north."

        local function foundThree()
            fleeWestThenClear()
            group("Ready")
            room(THREE)
        end

        it("fights when a move is refused for rest", function()
            foundThree()
            group("Ready")
            helper.simulateLine(REST)
            clearSent()
            room(THREE)
            assert.is_true(sent("confer kill champion"))
            assert.is_true(taPackage.teamElves.running())
        end)

        it("does not move on the poll that heals", function()
            foundThree()
            clearSent()
            group("Ready", 80)
            assert.is_true(sent("cast kusamotumaru"))
            assert.is_false(sent("e"))
        end)

        it("moves on a poll that is hurt but can't heal yet", function()
            foundThree()
            helper.simulateLine("You discharged the spell at friendly people in the area, healing 290 damage!")
            clearSent()
            group("Ready", 80)
            assert.is_false(sent("cast kusamotumaru"))
            assert.is_true(sent("e"))
        end)

        it("turns and fights when a champion arrives while it waits", function()
            foundThree()
            helper.simulateLine(ARRIVED)
            clearSent()
            room(ONE)
            assert.is_true(sent("confer kill champion"))
        end)

        it("still goes home after beating them", function()
            foundThree()
            helper.simulateLine(ARRIVED)
            room(ONE)
            kill()
            room(NONE)
            clearSent()
            group("Ready")
            assert.is_true(sent("e"))
            room(NONE)
            assert.is_false(taPackage.teamElves.running())
        end)
    end)

    it("clears a kill loop whose target walked out, so the next scan restarts it", function()
        start()
        helper.simulateLine('Sorry, you don\'t see "champion" nearby.')
        assert.is_falsy(taPackage.killActive)
        clearSent()
        room(ONE)
        assert.is_true(sent("confer kill champion"))
    end)

    it("ignores everything once it has stopped", function()
        start()
        helper.simulateAlias("stop-team-fight-elves")
        clearSent()
        kill()
        room(THREE)
        group("Ready", 10)
        assert.is_nil(next(helper.sendCalls))
    end)

    it("stop-team-fight-elves stands the group down", function()
        start()
        clearSent()
        helper.simulateAlias("stop-team-fight-elves")
        assert.is_true(sent("confer kill-stop"))
        assert.is_false(taPackage.teamElves.running())
        assert.is_falsy(taPackage.killActive)
    end)

    describe("loopNext", function()
        local nextExit = function(...) return taPackage.teamElves.loopNext(...) end

        it("starts north on a north-south side and east on an east-west one", function()
            assert.are.equal("n", nextExit({ "n", "s" }, nil))
            assert.are.equal("e", nextExit({ "e", "w" }, nil))
        end)

        it("follows the ring once it has a heading", function()
            assert.are.equal("w", nextExit({ "e", "w" }, "w"))
            assert.are.equal("e", nextExit({ "s", "e" }, "n"))
        end)

        it("picks a side at the top of the spur", function()
            assert.are.equal("e", nextExit({ "e", "s", "w" }, "n"))
        end)

        it("gives up at a dead end", function()
            assert.is_nil(nextExit({ "s" }, "n"))
        end)
    end)

    describe("in a loop", function()
        local function startLoop(occupants)
            helper.simulateAlias("team-fight-elves-in-loop")
            room(occupants)
        end

        local function clearHere()
            kill()
            room(TWO)
            kill()
            room(ONE)
            kill()
            room(NONE)
        end

        it("walks north from an empty room once everyone is Ready", function()
            startLoop(NONE)
            assert.is_true(taPackage.teamElves.running())
            group("Resting", 100, "n,s")
            assert.is_false(sent("n"))
            group("Ready", 100, "n,s")
            assert.is_true(sent("n"))
        end)

        it("walks east on an east-west side", function()
            startLoop(NONE)
            group("Ready", 100, "e,w")
            assert.is_true(sent("e"))
        end)

        it("walks past empty rooms and fights the first champions it finds", function()
            startLoop(NONE)
            group("Ready", 100, "n,s")
            room(NONE)
            clearSent()
            group("Ready", 100, "n,s")
            assert.is_true(sent("n"))
            assert.is_false(sent("confer kill champion"))
            arrive(THREE)
            assert.is_true(sent("confer kill champion"))
        end)

        it("moves on round the corner once the room is clear", function()
            startLoop(NONE)
            group("Ready", 100, "n,s")
            arrive(THREE)
            clearHere()
            assert.is_true(taPackage.teamElves.running())
            assert.is_truthy(lastEcho():find("3 this loop", 1, true))
            clearSent()
            group("Ready", 100, "s,e")
            assert.is_true(sent("e"))
        end)

        it("fights the champions it was started among first", function()
            startLoop(THREE)
            assert.is_true(sent("confer kill champion"))
            clearHere()
            clearSent()
            group("Ready", 100, "n,s")
            assert.is_true(sent("n"))
        end)

        it("chases a fleeing champion, comes back, and carries on the same way", function()
            startLoop(NONE)
            group("Ready", 100, "e,w")
            arrive(THREE)
            helper.simulateLine("The elven champion has just gone to the south.")
            clearHere()
            group("Ready", 100, "e,s")
            arrive(ONE)
            kill()
            room(NONE)
            group("Ready", 100, "n,s")
            room(NONE)
            clearSent()
            group("Ready", 100, "e,s,w")
            assert.is_true(sent("e"))
        end)

        it("turns and fights a champion that catches it between rooms", function()
            startLoop(NONE)
            helper.simulateLine("An elven champion has just arrived from the west.")
            clearSent()
            room(ONE)
            assert.is_true(sent("confer kill champion"))
        end)

        it("stops to fight warriors on the way round", function()
            startLoop(NONE)
            group("Ready", 100, "e,w")
            clearSent()
            arrive(WARRIORS)
            assert.is_true(sent("confer kill warrior"))
        end)

        it("keeps going round, room after room", function()
            startLoop(NONE)
            for _ = 1, 3 do
                group("Ready", 100, "e,w")
                arrive(THREE)
                clearHere()
            end
            assert.is_true(taPackage.teamElves.running())
        end)

        it("stops at a dead end rather than guess", function()
            startLoop(NONE)
            group("Ready", 100, "n,s")
            room(NONE)
            group("Ready", 100, "s")
            assert.is_false(taPackage.teamElves.running())
        end)

        describe("the corner report", function()
            local function pushes()
                local bodies = {}
                for _, call in ipairs(helper.httpRequestCalls) do
                    if call.url:find("ntfy", 1, true) then
                        table.insert(bodies, call.options.body)
                    end
                end
                return bodies
            end

            -- The group helper lists Pelayo and Pollux.
            local function answer(pelayoXp, polluxXp)
                helper.simulateLine("Experience:   " .. pelayoXp)
                helper.simulateLine("From Pollux (to group): xp-is " .. polluxXp)
            end

            before_each(function()
                taPackage.character.setName("Pelayo")
            end)

            it("knows the corners by their exits", function()
                local cornerOf = taPackage.teamElves.cornerOf
                assert.are.equal("NW", cornerOf({ "s", "e" }))
                assert.are.equal("NE", cornerOf({ "s", "w" }))
                assert.are.equal("SE", cornerOf({ "n", "w" }))
                assert.are.equal("SW", cornerOf({ "n", "e" }))
                assert.is_nil(cornerOf({ "e", "w" }))
                assert.is_nil(cornerOf({ "e", "s", "w" }))
            end)

            it("asks everyone for their XP on leaving the SE corner", function()
                startLoop(NONE)
                clearSent()
                group("Ready", 100, "n,w")
                assert.is_true(sent("status"))
                assert.is_true(sent("confer report-xp"))
                assert.is_true(sent("n"))
            end)

            it("says nothing at the other corners", function()
                startLoop(NONE)
                clearSent()
                group("Ready", 100, "s,w")
                assert.is_false(sent("confer report-xp"))
            end)

            it("pushes the circuit's time and each character's XP gain", function()
                startLoop(NONE)
                group("Ready", 100, "n,w")
                answer(1000000, 500000)
                local first = pushes()
                assert.are.equal(1, #first)
                assert.is_truthy(first[1]:find("reached SE corner at", 1, true))
                assert.is_truthy(first[1]:find("first time round", 1, true))

                helper.advanceMs(50 * 60000)
                room(NONE)
                group("Ready", 100, "e,w")
                room(NONE)
                group("Ready", 100, "n,w")
                answer(1100000, 520400)
                local bodies = pushes()
                assert.are.equal(2, #bodies)
                assert.is_truthy(bodies[2]:find("last circuit took 50 minutes", 1, true))
                assert.is_truthy(bodies[2]:find("  - pelayo 100k", 1, true))
                assert.is_truthy(bodies[2]:find("  - pollux 20k", 1, true))
                assert.is_true(helper.httpRequestCalls[2].options.headers["X-Title"]
                    == "Elven Valley Update")
            end)

            it("sends without whoever doesn't answer", function()
                startLoop(NONE)
                group("Ready", 100, "n,w")
                helper.simulateLine("Experience:   1000000")
                assert.are.equal(0, #pushes())
                helper.fireTimers(15000)
                assert.are.equal(1, #pushes())
            end)

            -- Ready with no time gone by, so the move waits on the pace and the
            -- next poll comes back through the same step.
            it("reports a visit once, however many polls it takes to leave", function()
                startLoop(NONE)
                group("Ready", 100, "e,w")
                room(NONE)
                clearSent()
                for _ = 1, 2 do
                    helper.simulateLine("Your group currently consists of:")
                    helper.simulateLine("  Pelayo                         (L) [HE:100% ST:Ready]")
                    helper.simulateLine("Exits: n,w.")
